/**
 * `<base>/llms.txt` — the whole API surface as plain Markdown.
 *
 * starlight-llms-txt walks the `docs` content collection, which cannot see
 * injected routes (PLAN.md decision 10), so we render our own. It is also useful
 * on its own: one URL that gives a model the entire API.
 */

import type { APIRoute } from 'astro';
import context from 'virtual:starlight-pydocs/context';

import { getModel } from '../lib/data.ts';
import { PydocsError } from '../lib/errors.ts';
import { renderPackageMarkdown } from '../lib/markdown-doc.ts';
import { packageForPathname } from '../libs/route.ts';

export const GET: APIRoute = async ({ site, url }) => {
  const pkg = packageForPathname(context, url.pathname);
  if (pkg === undefined) {
    throw new PydocsError(`starlight-pydocs: no configured package serves ${url.pathname}`);
  }

  const model = await getModel(context, pkg.base);
  const origin = site === undefined ? url.origin : site.href.replace(/\/$/, '');
  const header = [
    `# ${pkg.label}`,
    '',
    `> API reference for the Python package \`${pkg.name}\`, generated by starlight-pydocs.`,
    `> Rendered pages: ${origin}${context.siteBase}/${pkg.base}/`,
    '',
  ].join('\n');

  return new Response(`${header}\n${renderPackageMarkdown(model, { includeSource: true })}`, {
    headers: { 'content-type': 'text/markdown; charset=utf-8' },
  });
};
