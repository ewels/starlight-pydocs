/**
 * Translation tables injected into Starlight through the plugin's `i18n:setup`
 * hook.
 *
 * `lib/strings.ts` is the English source of truth; this module only namespaces
 * its keys (`starlightPydocs.<key>`) so they can share Starlight's global
 * translation table. Each locale beyond `en` overlays only the keys it
 * translates and Starlight falls back to English for the rest, so a new string
 * ships usable everywhere the day it is added.
 *
 * Labels that name a Python or pydantic construct are deliberately absent from
 * every locale: `classmethod`, `staticmethod`, `async`, `abstract`, `cached` and
 * the three pydantic badges are the identifiers a reader sees in the code, and
 * translating them would name something that does not exist.
 *
 * The tables are typed against `StringKey`, so a renamed or removed string is a
 * type error here rather than a label that quietly falls back to English.
 */

import { translationKey } from './lib/i18n.ts';
import type { StringKey } from './lib/strings.ts';
import { STRINGS } from './lib/strings.ts';

type LocaleTable = Partial<Record<StringKey, string>>;

function namespaced(table: LocaleTable): Record<string, string> {
  const entries: [string, string][] = [];
  for (const key of Object.keys(table) as StringKey[]) {
    const value = table[key];
    if (value !== undefined) entries.push([translationKey(key), value]);
  }
  return Object.fromEntries(entries);
}

